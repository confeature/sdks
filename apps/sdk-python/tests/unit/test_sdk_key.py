"""Unit tests for `confeature_client.sdk_key` — redaction + cross-language cache key.

The cross-language fixture verification is the load-bearing gate for
spec 037 US2 (FR-010, SC-003). The TS workspace generates
`packages/test-fixtures-sdk-parity/fixtures/cache-key-fixtures.json`
via `deriveCacheKey` (SHA-256 path); the Python implementation MUST
produce byte-identical strings for every entry.
"""

from __future__ import annotations

import pytest

from confeature_client.sdk_key import (
    CACHE_KEY_PREFIX,
    derive_cache_key,
    is_valid_confeature_key_format,
    redact_sdk_key,
)


class TestRedactSdkKey:
    def test_none_returns_redacted(self) -> None:
        assert redact_sdk_key(None) == "[redacted]"

    def test_empty_returns_redacted(self) -> None:
        assert redact_sdk_key("") == "[redacted]"

    def test_short_key_returns_redacted(self) -> None:
        # < 16 chars → full mask.
        assert redact_sdk_key("short-key") == "[redacted]"

    def test_normal_key_keeps_head_and_tail(self) -> None:
        sdk_key = (
            "confeature-sdk-1-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA-BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB"
        )
        redacted = redact_sdk_key(sdk_key)
        assert "[redacted]" in redacted
        # Per the algorithm: visible = max(4, floor(len * 0.1)).
        # len(sdk_key) = 81; floor(8.1) = 8.
        visible = 8
        assert redacted.startswith(sdk_key[:visible])
        assert redacted.endswith(sdk_key[-visible:])
        assert sdk_key not in redacted  # raw key MUST never appear.

    def test_redacted_never_contains_full_key(self) -> None:
        sdk_key = (
            "confeature-sdk-1-ZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZZ-YYYYYYYYYYYYYYYYYYYYYYYYYYYYYYYY"
        )
        assert sdk_key not in redact_sdk_key(sdk_key)

    def test_configcat_shaped_key_shows_no_more_secret_than_before(self) -> None:
        """#802 FR-005: a ConfigCat-shaped key (61 chars, `/`-separated)
        keeps 6 chars at each end — the head is the public
        `config` prefix and the tail 6 secret chars, fewer than the 8 a
        legacy key shows. Neither secret segment appears whole."""
        sdk_key = "configcat-sdk-1/FAKEfixtureKeyNotRea01/FAKEfixtureKeyNotRea02"
        redacted = redact_sdk_key(sdk_key)
        assert redacted == "config…[redacted]…tRea02"
        assert "FAKEfixtureKeyNotRea01" not in redacted
        assert "FAKEfixtureKeyNotRea02" not in redacted


class TestIsValidConfeatureKeyFormat:
    def test_canonical_key_is_valid(self) -> None:
        assert is_valid_confeature_key_format(
            "confeature-sdk-1-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA-BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB"
        )

    def test_configcat_dash_separated_key_is_invalid(self) -> None:
        # ConfigCat's shape separates its segments with `/`, not `-`: a
        # dash-joined `configcat-sdk-1-…` is neither shape. Lenient at
        # runtime, but the format validator says "no".
        assert not is_valid_confeature_key_format(
            "configcat-sdk-1-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA-BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB"
        )

    def test_empty_key_is_invalid(self) -> None:
        assert not is_valid_confeature_key_format("")

    def test_accepts_every_valid_shape(
        self, sdk_key_shapes: dict[str, list[dict[str, str]]]
    ) -> None:
        """#802 FR-004/FR-006b: both the ConfigCat-shaped key Confeature now
        mints and the legacy shape are accepted — cases from the shared list."""
        rejected = [
            c["name"]
            for c in sdk_key_shapes["valid"]
            if not is_valid_confeature_key_format(c["key"])
        ]
        assert not rejected, f"valid shapes rejected: {rejected}"

    def test_rejects_every_invalid_shape(
        self, sdk_key_shapes: dict[str, list[dict[str, str]]]
    ) -> None:
        accepted = [
            c["name"] for c in sdk_key_shapes["invalid"] if is_valid_confeature_key_format(c["key"])
        ]
        assert not accepted, f"invalid shapes accepted: {accepted}"


class TestDeriveCacheKey:
    def test_envelope_prefix(self) -> None:
        key = derive_cache_key("some-key")
        assert key.startswith(CACHE_KEY_PREFIX)
        assert len(key) == len(CACHE_KEY_PREFIX) + 32

    def test_deterministic(self) -> None:
        assert derive_cache_key("alpha") == derive_cache_key("alpha")

    def test_distinct_inputs_distinct_outputs(self) -> None:
        assert derive_cache_key("alpha") != derive_cache_key("beta")

    def test_cross_language_fixture(self, cache_key_fixtures: list[dict[str, str]]) -> None:
        """Spec 037 FR-010 / SC-003: byte-identical against TS deriveCacheKey.

        Reads `cache-key-fixtures.json` generated by
        `packages/test-fixtures-sdk-parity/scripts/export-cache-key-fixtures.ts`.
        Asserts byte-equal output for every entry.
        """
        assert len(cache_key_fixtures) >= 5, (
            "Spec 037 FR-010 requires ≥ 5 cache-key fixture entries; "
            f"found {len(cache_key_fixtures)}. Regenerate via "
            "'pnpm run export:cache-key-fixtures'."
        )
        mismatches: list[str] = []
        for entry in cache_key_fixtures:
            sdk_key = entry["sdkKey"]
            expected = entry["expectedCacheKey"]
            actual = derive_cache_key(sdk_key)
            if actual != expected:
                mismatches.append(f"sdkKey={sdk_key!r}: TS={expected!r} ≠ Py={actual!r}")
        assert not mismatches, "TS vs Py cache-key drift: " + "; ".join(mismatches)


@pytest.mark.parametrize(
    ("sdk_key", "expected_cache_key"),
    [
        # Echo the canonical fixture entries — also runs as parametrized cases
        # so the failure mode is per-input, not per-fixture-file.
        (
            "confeature-sdk-1-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA-BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB",
            "confeature:cache:v1:bIg57I9_4ya_LRRpZZ8qZdn_gXPqQ1aY",
        ),
        ("", "confeature:cache:v1:47DEQpj8HBSa-_TImW-5JCeuQeRkm5NM"),
    ],
)
def test_derive_cache_key_known_values(sdk_key: str, expected_cache_key: str) -> None:
    assert derive_cache_key(sdk_key) == expected_cache_key
